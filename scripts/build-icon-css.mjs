#!/usr/bin/env node
/**
 * Generates public/salary-compass/icons.css — a drop-in replacement for the
 * Font Awesome stylesheet that page used to pull from assets.softr-files.com.
 *
 * That CDN dies with the Softr subscription, and it was serving the icons on the
 * highest-value page on the site. Self-hosting the real Font Awesome webfonts
 * would cost ~236 KB for ten glyphs, so this emits mask-image rules instead:
 * same class names, same markup, ~6 KB, and the icons inherit currentColor so
 * every existing colour rule keeps working.
 *
 * Run after `npm i @fortawesome/fontawesome-free --no-save` when the icon list
 * changes. The output is committed, so a normal build needs neither.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FA = join(ROOT, 'node_modules/@fortawesome/fontawesome-free/svgs');

// Exactly what public/salary-compass/index.html uses. Keep in sync — an icon
// missing here renders as an empty box, which is easy to miss in review.
const ICONS = [
  ['brands', 'linkedin'],
  ['brands', 'linkedin-in'],
  ['brands', 'slack'],
  ['brands', 'whatsapp'],
  ['brands', 'x-twitter'],
  ['solid', 'download'],
  ['solid', 'envelope'],
  ['solid', 'link'],
  ['solid', 'lock'],
  ['solid', 'share-nodes'],
];

/** Data URIs must not contain raw #, < or > or the CSS parser truncates them. */
function toDataUri(svg) {
  const cleaned = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `url("data:image/svg+xml,${encodeURIComponent(cleaned)}")`;
}

const rules = ICONS.map(([style, name]) => {
  const svg = readFileSync(join(FA, style, `${name}.svg`), 'utf8');
  return `.fa-${name}{--fa-icon:${toDataUri(svg)}}`;
});

const css = `/* GENERATED by scripts/build-icon-css.mjs — do not edit by hand.
 *
 * Replaces the Font Awesome stylesheet that was hotlinked from Softr's CDN.
 * Ten icons as masks rather than a webfont: ~6 KB instead of ~236 KB, and they
 * take their colour from currentColor so existing rules still apply.
 */
.fa,.fas,.fab,.far{
  display:inline-block;
  width:1em;
  height:1em;
  vertical-align:-0.125em;
  background-color:currentColor;
  -webkit-mask-image:var(--fa-icon);mask-image:var(--fa-icon);
  -webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;
  -webkit-mask-position:center;mask-position:center;
  -webkit-mask-size:contain;mask-size:contain;
}
/* The real Font Awesome draws through ::before; these draw through the element
 * itself, so any inherited content rule has to be cancelled or it doubles. */
.fa::before,.fas::before,.fab::before,.far::before{content:none}
${rules.join('\n')}
`;

const out = join(ROOT, 'public/salary-compass/icons.css');
writeFileSync(out, css);
console.log(`✓ icons.css — ${ICONS.length} icons, ${(css.length / 1024).toFixed(1)} KB`);
